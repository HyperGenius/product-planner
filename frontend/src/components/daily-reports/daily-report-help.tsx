"use client"

import { PageHelp, PageHelpSection } from "@/components/page-help"
import { DEFAULT_PERIOD_MONTHS } from "@/lib/daily-report-coverage-utils"
import { STOCK_LABEL } from "@/lib/daily-report-stock-utils"
import {
  DAILY_REPORT_ALIASES_LABEL,
  DAILY_REPORT_HUB_TITLE,
} from "@/lib/daily-report-worklist-utils"

/**
 * 日報の実績のヘルプ（Issue #707 / #702）。判定条件・データの出どころ・状態の移り変わり・設計上の原則は画面に書かず、
 * ここにまとめる（docs/ui-writing-guidelines.md の2章・7章）。ハブと各ページで共有する。
 * 各ページの行・ダイアログから外した説明（結び付けの単位・並び順・承認前の受注・対象外の戻し方）もここに置く
 */
export function DailyReportHelp() {
  return (
    <PageHelp title={DAILY_REPORT_HUB_TITLE}>
      <PageHelpSection title="片付ける順">
        <p>
          日報の実績を受注の進捗に結び付けるには、日報の顧客先 → 製品 → 工程の順にアプリの顧客・製品・工程と結び付けます。
          顧客先が決まらないと製品を結び付けられず、製品が決まらないと工程ルートと比べられないので、前提 → ① → ② → ③
          の順に進めます。
        </p>
        <p>日報の表記・実績は、前提・①②③・参考のどれか1か所にだけ数えています。</p>
      </PageHelpSection>
      <PageHelpSection title="日報の顧客先（前提）">
        <p>
          日報の顧客先の表記のうち、アプリの顧客に結び付いていないものです。製品の結び付けは顧客ごとなので、
          顧客先が決まっていない日報の製品もここに置き、①には数えません。
        </p>
        <p>
          未登録の顧客先ごとに、その顧客先の製品をまとめています。顧客を選ぶと、その顧客先の製品は①に移ります。
          件数は未登録の顧客先の数で、製品の行が無い顧客先も数えます（日報の顧客先は受注の顧客と比べるため）。
        </p>
        <p>
          顧客先が空欄の製品と、対象外にした顧客先の製品は顧客を選べないので、別にまとめています。対象外にするか、
          日報の顧客先を書いてもらってください。対象外にした顧客先は「登録済みの対応付け・対象外」から戻せます。
        </p>
      </PageHelpSection>
      <PageHelpSection title="① 日報の製品をつなぐ">
        <p>
          顧客先が決まっている日報の製品の表記のうち、製品マスタに結び付いていないものです。顧客先と商品名の組ごとに1行です。
          1回結び付けると、過去・今後の日報にも反映されます。
        </p>
        <p>
          製品は顧客ごとに結び付けます。同じ商品名でも顧客先が違えば、それぞれ結び付けます。顧客先が未登録の製品は前提のページにまとめています。製品の結び付けはメール起票と共通で、変更・削除はメール起票の読み取りにも効きます。
        </p>
        <p>
          行には、その顧客の確定済み・生産中の受注のうち、日報の実績がまだ1つも結び付いていない受注の製品を、日報の商品名に近い順に3件まで並べています。
          4件目からは「他の製品から選択」の「受注の製品」にあります。受注の製品に無いときは「似ている製品」（製品マスタ全体から品名の似ている順）か
          「すべての製品」から選びます。
        </p>
        <p>
          受注の製品にも製品マスタにも無い新しい製品は「製品を登録する」で製品マスタに登録し、そのまま日報の商品名を結び付けます。
          品名は日報の商品名から始まり、図番は商品名に図番らしき番号（5桁以上の数字）が1つだけあるときに入ります。
          似た製品があれば、作らずにその製品へ結び付けられます。登録した製品の工程ルートは、次の集計の後に②で合わせます。
        </p>
        <p>
          結び付けた実績は次の集計で受注に結び付くので、それまでは同じ製品が他の行の受注の製品にも残ります。同じ製品に別の書き方の商品名を結び付けても構いません。
        </p>
        <p>
          製品を選ぶと、その顧客のその製品の確定済み・生産中の受注を出します。承認前（下書き・承認待ち）の受注には実績を結び付けず、
          承認後の集計で結び付けます。
        </p>
      </PageHelpSection>
      <PageHelpSection title="並び順">
        <p>
          日報の表記は、その表記が書かれた日報の明細の多い順に並べています（同じ数なら最後に書かれた日が新しい順）。
        </p>
      </PageHelpSection>
      <PageHelpSection title="② 製品の工程を日報に合わせる">
        <p>
          製品の工程ルートが無い製品、日報の工程が工程ルートに無い製品、日報で追わない工程に実績がある製品です。製品ごとに1行です。
        </p>
        <p>
          工程マスタに無い日報の工程名もここに置きます。工程名の結び付けは製品によらず共通です。
        </p>
      </PageHelpSection>
      <PageHelpSection title="③ 受注の無い製造を確かめる">
        <p>
          製品・工程まで結び付いたのに、受注に結び付かなかった実績です。製品・工程名・理由ごとに1行で、
          現場に聞くことを添えています。
        </p>
      </PageHelpSection>
      <PageHelpSection title="期間">
        <p>
          ②③は加工日が直近{DEFAULT_PERIOD_MONTHS}か月（今月を含む）の実績で数えます。②③のページで期間を変えると、そのページの件数も変わります。
          加工日が空欄の実績は期間にかかわらず含めます。①・前提は期間で絞りません。
        </p>
      </PageHelpSection>
      <PageHelpSection title={`${STOCK_LABEL}（参考）`}>
        <p>
          受注に結び付いていない、作っておいた品物の推定数です。日報からの推定で、正確な数は目指していません。
          工程ごとに、次の工程で使われたら減り、最後の工程なら送品で減るとみなしています。現場の実態と違うところは「違う」で直してください。
        </p>
        <p>
          「違う」で実際の数を入れると、数えた日の作業を終えた時点の数として、それ以降の日報で増減させます。
        </p>
      </PageHelpSection>
      <PageHelpSection title="結び付いた割合（参考）">
        <p>
          日報の良品数のうち、受注の工程に結び付いた数の割合です。1行が2つの工程にまたがる表記（「カシメ、仕上げ加工」など）は工程ごとに数えます。
        </p>
      </PageHelpSection>
      <PageHelpSection title="反映のタイミング">
        <p>
          日報の取り込み後、10〜15分ごとに集計します。結び付け・工程の変更・{STOCK_LABEL}の指摘は、次の集計で②③と{STOCK_LABEL}に反映されます。
          ①・前提は結び付けたときにすぐ変わります。
        </p>
      </PageHelpSection>
      <PageHelpSection title="対象外・登録済みの対応付け">
        <p>
          結び付ける必要のない表記（試作・社内の作業など）は「対象外」にすると、前提・①②に出なくなります。
          戻すには、対象外にした直後のお知らせの「元に戻す」か、「{DAILY_REPORT_ALIASES_LABEL}」の「対象外」タブの「戻す」を押します。
        </p>
        <p>
          登録済みの対応付けを削除すると、マスタに結び付かなくなった表記は前提・①②に戻ります。
        </p>
      </PageHelpSection>
      <PageHelpSection title="日報の設備">
        <p>
          設備は受注の進捗の計算に使わないので、ここには数えません。設備の表記は「登録済みの対応付け・対象外」のページで結び付けます。
        </p>
      </PageHelpSection>
    </PageHelp>
  )
}
